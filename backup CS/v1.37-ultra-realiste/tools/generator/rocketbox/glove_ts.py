"""v0.43: the sculpted boxing glove (glove.py) for the Anime coaches, written as src/three/gloveShape.ts.
python3 tools/generator/rocketbox/glove_ts.py [triangles]
The shape is the same as the Ultra-réaliste glove, lighter (the Anime render is flat: about 2,400 triangles),
in the hand frame of the reference hand (x toward the knuckles, y toward the index, z out of the back of the hand),
positions in tenths of a millimetre (int16), base64."""
import os, sys, base64, struct
import bpy, bmesh
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glove as GL

tris = int(sys.argv[1]) if len(sys.argv) > 1 else 2400
v, q, _, _ = GL.glove_mesh(step=0.0024)
bm_ = bmesh.new()
vs = [bm_.verts.new(tuple(p)) for p in v]
for f in q:
    try:
        bm_.faces.new([vs[i] for i in f])
    except ValueError:
        pass
bmesh.ops.recalc_face_normals(bm_, faces=bm_.faces[:])
me = bpy.data.meshes.new('g')
bm_.to_mesh(me)
o = bpy.data.objects.new('g', me)
bpy.context.collection.objects.link(o)
bpy.context.view_layer.objects.active = o
o.select_set(True)
for kind, opt in (('TRIANGULATE', {}), ('DECIMATE', {'ratio': tris / (2 * len(q))})):
    m = o.modifiers.new(kind, kind)
    for k_, x in opt.items():
        setattr(m, k_, x)
    bpy.ops.object.modifier_apply(modifier=m.name)
pos = np.array([vv.co[:] for vv in me.vertices])
reg, _ = GL.regions(pos)
idx = [i for p in me.polygons for i in p.vertices]
qp = np.round(pos * 10000).astype('<i2')
out = os.path.join(os.path.dirname(__file__), '../../../src/three/gloveShape.ts')
b64 = lambda b: base64.b64encode(b).decode()
with open(out, 'w') as f:
    f.write('// generated by tools/generator/rocketbox/glove_ts.py: do not edit\n')
    f.write('// v0.43 sculpted boxing glove, hand frame of the reference hand (wrist to middle knuckle 9.5 cm)\n')
    f.write('// x toward the knuckles, y toward the index, z out of the back of the hand; positions in 0.1 mm\n')
    f.write(f'export const GLOVE_POSITIONS = \'{b64(qp.tobytes())}\';\n')
    f.write(f'export const GLOVE_INDEX = \'{b64(np.array(idx, "<u2").tobytes())}\';\n')
    f.write(f'/** 0 leather, 1 strap, 2 lining, one byte per point */\n')
    f.write(f'export const GLOVE_REGION = \'{b64(reg.astype("u1").tobytes())}\';\n')
print('gloveShape.ts', len(pos), 'points', len(idx) // 3, 'triangles', os.path.getsize(out), 'bytes')
