  it("l'identifiant ne dépend plus de la position : discipline, niveau et numéro écrits en dur", () => {
    for (const e of EXERCISES) expect(e.id.startsWith(`${e.discipline}-${e.level}-`), e.id).toBe(true);
    // un exercice inséré en tête d'un niveau ne décale plus les autres : les numéros ne suivent pas forcément l'ordre
    const src = readFileSync('src/domain/exercises.ts', 'utf8');
    expect(src).not.toMatch(/padStart\(2, '0'\)/);
    expect((src.match(/^    \['[a-z]+-[a-z]+-\d{2,}', /gm) ?? []).length).toBe(EXERCISES.length);
  });
